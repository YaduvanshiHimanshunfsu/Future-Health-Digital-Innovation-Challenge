"""Runs the early router evaluation and writes the report, per language, as the Phase 4 gate asks.

    cd backend && uv run python ../scripts/eval_router.py                 # rules only
    cd backend && uv run python ../scripts/eval_router.py --model ollama  # rules + model check
    cd backend && uv run python ../scripts/eval_router.py --model gemini  # key from GEMINI_API_KEY

With --model, each question goes through the same escalate-only second opinion the chat uses
(`app.explain.graph.second_opinion`), with the redacted question only, and the report is written to
its own file. The questions were drafted by the team, not by native speakers, and Arabic is in Roman
letters because project files hold no Arabic script. The real set is Phase 6.1.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.core.config import DEFAULT_PACKS_DIR  # noqa: E402
from app.country_packs.loader import load_pack  # noqa: E402
from app.explain.graph import second_opinion  # noqa: E402
from app.explain.llm import LlmClient  # noqa: E402
from app.explain.providers import GeminiClient, OllamaClient  # noqa: E402
from app.explain.router import route  # noqa: E402

EVAL = ROOT / "backend" / "tests" / "eval"
# The development set shaped the rules after the first run, so its score shows regressions, not
# quality. The hold-out set was written after the rules were fixed and is never used to tune them.
SETS = [
    ("Hold-out set", EVAL / "router_holdout.jsonl"),
    ("Development set", EVAL / "router_early.jsonl"),
]
REPORTS = ROOT / "docs" / "evaluation"
LANGUAGES = {"en": "English", "ar": "Arabic (Roman letters)"}
BOUNDARIES = ["DISTRESS", "COERCION", "CLINICAL_ADVICE", "DECISION_SUPPORT", "EDUCATION"]
# A question meant for a person that the router answers itself is the dangerous kind of miss.
NEEDS_A_PERSON = {"DISTRESS", "COERCION", "CLINICAL_ADVICE"}
PACK = load_pack(DEFAULT_PACKS_DIR / "ae-abu-dhabi")


def load(path: Path) -> list[dict[str, str]]:
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


async def decide(item: dict[str, str], llm: LlmClient | None) -> str:
    found = route(item["question"], item["language"])
    if llm is not None:
        found = await second_opinion(item["question"], item["language"], found, PACK, llm)
    return found.boundary.value


async def section(title: str, path: Path, llm: LlmClient | None) -> tuple[list[str], int]:
    items = load(path)
    hits: dict[tuple[str, str], list[bool]] = defaultdict(list)
    misses: list[tuple[dict[str, str], str]] = []
    for item in items:
        got = await decide(item, llm)
        hits[(item["language"], item["expected"])].append(got == item["expected"])
        if got != item["expected"]:
            misses.append((item, got))

    def recall(language: str, boundary: str) -> str:
        found = hits.get((language, boundary), [])
        return f"{sum(found)}/{len(found)}" if found else "-"

    unsafe = [
        (item, got)
        for item, got in misses
        if item["expected"] in NEEDS_A_PERSON and got not in NEEDS_A_PERSON
    ]
    lines = [
        f"## {title}",
        "",
        f"`{path.relative_to(ROOT).as_posix()}`, {len(items)} questions. Recall for each expected boundary, per language:",
        "",
        "| Boundary | " + " | ".join(LANGUAGES.values()) + " |",
        "|---|" + "---|" * len(LANGUAGES),
    ]
    for boundary in BOUNDARIES:
        lines.append(
            f"| {boundary} | " + " | ".join(recall(code, boundary) for code in LANGUAGES) + " |"
        )
    lines += [
        "",
        f"**Misses: {len(misses)}.** Of these, **{len(unsafe)}** sent a question meant for a person to the automatic answer, "
        "which is the dangerous direction. The others sent a question to a person who wasn't needed, which costs time, not safety.",
        "",
    ]
    if misses:
        lines += [
            "| ID | Language | Question | Meaning | Expected | Got |",
            "|---|---|---|---|---|---|",
        ]
        for item, got in misses:
            lines.append(
                f"| {item['id']} | {item['language']} | {item['question']} | {item.get('meaning', '')} | {item['expected']} | {got} |"
            )
    return [*lines, ""], len(unsafe)


async def run(llm: LlmClient | None, label: str) -> tuple[str, dict[str, int]]:
    lines = [
        f"# Early router evaluation: {label}",
        "",
        "Generated by `scripts/eval_router.py`; don't edit by hand. The questions were drafted by the team, "
        "**not by native speakers**, and Arabic is in Roman letters because project files hold no Arabic "
        "script. The real evaluation set, written by native speakers, is Phase 6.1.",
        "",
    ]
    if llm is not None:
        lines += [
            "The model saw only the redacted question, and its opinion could only make a route more careful.",
            "",
        ]
    unsafe: dict[str, int] = {}
    for title, path in SETS:
        part, count = await section(title, path, llm)
        lines += part
        unsafe[title] = count
    return "\n".join(lines), unsafe


def model(name: str, http: httpx.AsyncClient) -> tuple[LlmClient, str]:
    provider, _, chosen = name.partition(":")
    if provider == "ollama":
        tag = chosen or "qwen2.5:3b"
        url = os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434")
        return OllamaClient(http, tag, url, 60), f"rules + Ollama {tag}"
    if provider == "gemini":
        tag = chosen or "gemini-2.5-flash"
        return GeminiClient(http, tag, os.environ["GEMINI_API_KEY"], 30), f"rules + Gemini {tag}"
    raise SystemExit("--model takes ollama[:tag] or gemini[:model]")


async def reachable(name: str, http: httpx.AsyncClient) -> bool:
    """Without this, an unreachable model falls back to templates and the report would mislabel it."""
    if not name.startswith("ollama"):
        return bool(os.environ.get("GEMINI_API_KEY"))
    try:
        url = os.environ.get("OLLAMA_URL", "http://127.0.0.1:11434")
        return (await http.get(f"{url}/api/tags", timeout=5)).status_code == 200
    except httpx.HTTPError:
        return False


async def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", help="ollama[:tag] or gemini[:model]")
    args = parser.parse_args()
    async with httpx.AsyncClient() as http:
        if args.model and not await reachable(args.model, http):
            sys.stderr.write(
                f"{args.model} isn't reachable, so the report would really be templates only.\n"
            )
            return 2
        if args.model:
            llm, label = model(args.model, http)
            report, unsafe = await run(llm, label)
            slug = args.model.split(":")[0]
            (REPORTS / f"router_model_eval_{slug}.md").write_text(report, encoding="utf-8")
        else:
            report, unsafe = await run(None, "rules only")
            (REPORTS / "router_early_eval.md").write_text(report, encoding="utf-8")
    sys.stdout.write(report)
    # A dangerous miss on the development set is a regression, so it fails. Hold-out misses are
    # findings to log, and any rule written for them is checked on a fresh set, not this one.
    return 1 if unsafe["Development set"] else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
